const SCENE_STATE_KEYS = [
    'close',
    'project01',
    'project02',
    'project03',
    'project04',
    'project05',
]

function mergeSceneState(
    defaultState,
    savedState,
) {
    return {
        ...defaultState,
        ...savedState,

        camera: {
            ...defaultState.camera,
            ...savedState?.camera,
        },

        orbit: {
            ...defaultState.orbit,
            ...savedState?.orbit,
        },

        onyx: {
            ...defaultState.onyx,
            ...savedState?.onyx,
        },

        project01: {
            ...defaultState.project01,
            ...savedState?.project01,
        },

        project02: {
            ...defaultState.project02,
            ...savedState?.project02,
        },

        project03: {
            ...defaultState.project03,
            ...savedState?.project03,
        },

        project04: {
            ...defaultState.project04,
            ...savedState?.project04,
        },

        project05: {
            ...defaultState.project05,
            ...savedState?.project05,
        },

        nebula: {
            ...defaultState.nebula,
            ...savedState?.nebula,
        },
    }
}

export function cloneSceneStates(
    states = defaultSceneStates,
) {
    return JSON.parse(
        JSON.stringify(states),
    )
}

export function loadSceneStates() {
    const defaults =
        cloneSceneStates()

    if (
        typeof window === 'undefined'
    ) {
        return defaults
    }

    try {
        const saved =
            JSON.parse(
                window.localStorage.getItem(
                    SCENE_STATE_STORAGE_KEY,
                ),
            )

        if (!saved) {
            return defaults
        }

        return SCENE_STATE_KEYS.reduce(
            (result, key) => {
                result[key] =
                    mergeSceneState(
                        defaults[key],
                        saved[key],
                    )

                return result
            },
            {},
        )
    } catch {
        return defaults
    }
}
